// Codex Gateway Launcher
// Opens a separate VS Code instance (own --user-data-dir) with CODEX_HOME pointing at a dedicated
// Codex home whose config.toml uses an OpenAI-compatible gateway. The gateway key lives in VS Code
// SecretStorage and is handed to the new instance only through its environment.
// Nothing here reads or writes ~/.codex or the official Codex extension's state.
const vscode = require('vscode');
const cp = require('child_process');
const fs = require('fs');
const os = require('os');
const path = require('path');
const http = require('http');
const https = require('https');

const VIEW_ID = 'codexGateway.launcher';
const SECRET = 'codexGateway.apiKey';
const ENV_KEY = 'CODEX_GATEWAY_API_KEY';
const PROVIDER = 'gateway';
let lastLaunch = 0;

const cfg = () => vscode.workspace.getConfiguration('codexGateway');
const expand = (p) => (p && p.startsWith('~') ? path.join(os.homedir(), p.slice(1)) : p);
const codexHome = () => path.resolve(expand(cfg().get('codexHome') || '~/.codex-gateway'));
const baseUrl = () => String(cfg().get('baseUrl') || '').trim().replace(/\/+$/, '');
const inside = () => path.resolve(process.env.CODEX_HOME || '/nonexistent') === codexHome();

function configToml() {
  return [
    '# Generated by the Codex Gateway Launcher extension.',
    '# Separate Codex home: the official app / extension keep using ~/.codex.',
    `model = ${JSON.stringify(cfg().get('defaultModel') || 'gpt-6.1-sol')}`,
    `model_provider = "${PROVIDER}"`,
    '',
    `[model_providers.${PROVIDER}]`,
    'name = "Gateway"',
    `base_url = ${JSON.stringify(baseUrl())}`,
    `env_key = "${ENV_KEY}"`,
    'wire_api = "responses"',
    '',
  ].join('\n');
}

// Creates the Codex home and its config.toml. An existing config is kept unless force is set
// (then the old file is saved next to it as config.toml.bak).
function ensureConfig(force) {
  const home = codexHome();
  fs.mkdirSync(home, { recursive: true, mode: 0o700 });
  const file = path.join(home, 'config.toml');
  if (fs.existsSync(file)) {
    if (!force) return file;
    fs.copyFileSync(file, file + '.bak');
  }
  fs.writeFileSync(file, configToml(), { mode: 0o600 });
  return file;
}

function configMismatch() {
  try {
    const text = fs.readFileSync(path.join(codexHome(), 'config.toml'), 'utf8');
    return !text.includes(`base_url = ${JSON.stringify(baseUrl())}`);
  } catch { return false; }
}

function codeCli() {
  const bin = path.join(vscode.env.appRoot, 'bin');
  for (const name of process.platform === 'win32' ? ['code.cmd', 'code-insiders.cmd'] : ['code', 'code-insiders', 'codium']) {
    const p = path.join(bin, name);
    if (fs.existsSync(p)) return p;
  }
  return undefined;
}

function request(url, key) {
  return new Promise((resolve) => {
    let u;
    try { u = new URL(url); } catch { return resolve({ error: '网关地址不是合法的 URL' }); }
    const req = (u.protocol === 'http:' ? http : https).request(
      u, { method: 'GET', headers: { Authorization: `Bearer ${key}` }, timeout: 15000 },
      (res) => {
        let body = '';
        res.on('data', (d) => { if (body.length < 2e6) body += d; });
        res.on('end', () => resolve({ status: res.statusCode, body }));
      });
    req.on('timeout', () => req.destroy(new Error('15 秒内没有响应')));
    req.on('error', (e) => resolve({ error: e.message }));
    req.end();
  });
}

async function testGateway(context, quiet) {
  const key = inside() ? process.env[ENV_KEY] : await context.secrets.get(SECRET);
  if (!baseUrl()) { vscode.window.showWarningMessage('还没有填写网关地址。'); return false; }
  if (!key) { vscode.window.showWarningMessage('还没有填写网关 key。'); return false; }
  const r = await request(baseUrl() + '/models', key);
  if (r.error) { vscode.window.showErrorMessage(`连不上网关 ${baseUrl()}: ${r.error}`); return false; }
  if (r.status === 401 || r.status === 403) { vscode.window.showErrorMessage(`网关拒绝了这个 key (HTTP ${r.status})。`); return false; }
  if (r.status !== 200) { vscode.window.showErrorMessage(`网关返回 HTTP ${r.status}。请检查网关地址是否以 /v1 结尾。`); return false; }
  let n = '?';
  try { n = JSON.parse(r.body).data.length; } catch { /* not a model list; still reachable */ }
  if (!quiet) vscode.window.showInformationMessage(`网关连接正常,key 有效,可用模型 ${n} 个。`);
  return true;
}

async function refreshContext(context) {
  await vscode.commands.executeCommand('setContext', 'codexGateway.inside', inside());
  await vscode.commands.executeCommand('setContext', 'codexGateway.hasUrl', !!baseUrl());
  await vscode.commands.executeCommand('setContext', 'codexGateway.hasKey', !!(await context.secrets.get(SECRET)));
}

async function setUrl(context) {
  const value = await vscode.window.showInputBox({
    title: '网关地址', prompt: 'OpenAI 兼容地址,以 /v1 结尾', placeHolder: 'https://gateway.example.com/v1',
    value: baseUrl(), ignoreFocusOut: true,
    validateInput: (v) => { try { const u = new URL(v.trim()); return /^https?:$/.test(u.protocol) ? undefined : '需要 http(s) 地址'; } catch { return '不是合法的 URL'; } },
  });
  if (!value) return false;
  await cfg().update('baseUrl', value.trim().replace(/\/+$/, ''), vscode.ConfigurationTarget.Global);
  await refreshContext(context);
  return true;
}

async function setKey(context) {
  if (!baseUrl() && !(await setUrl(context))) return false;
  const value = await vscode.window.showInputBox({
    title: '网关 key', prompt: `用于 ${baseUrl()} 的 key(例如 sk-bf-…)`, password: true, ignoreFocusOut: true,
    validateInput: (v) => (v.trim().length < 8 || /\s/.test(v.trim()) ? '看起来不是一个有效的 key' : undefined),
  });
  if (!value) return false;
  await context.secrets.store(SECRET, value.trim());
  await refreshContext(context);
  await testGateway(context, false);
  return true;
}

async function launch(context, folder) {
  if (inside()) { vscode.window.showInformationMessage('当前窗口已经是网关实例。'); return; }
  const now = Date.now();
  if (now - lastLaunch < 3000) return; // debounce double triggers
  lastLaunch = now;

  if (!baseUrl() && !(await setUrl(context))) return;
  let key = await context.secrets.get(SECRET);
  if (!key) {
    if (!(await setKey(context))) return;
    key = await context.secrets.get(SECRET);
  }
  if (!vscode.extensions.getExtension('openai.chatgpt')) {
    const go = await vscode.window.showWarningMessage('没有安装官方 Codex 插件 (openai.chatgpt),网关实例里将没有 Codex 界面。', '仍然打开', '取消');
    if (go !== '仍然打开') return;
  }
  const cli = codeCli();
  if (!cli) { vscode.window.showErrorMessage(`在 ${vscode.env.appRoot}/bin 下找不到 VS Code 命令行。`); return; }

  let home;
  try {
    ensureConfig(false);
    home = codexHome();
  } catch (e) { vscode.window.showErrorMessage(`无法写入 Codex 配置目录: ${e.message}`); return; }
  if (configMismatch()) {
    const pick = await vscode.window.showWarningMessage('网关实例现有的 config.toml 里的网关地址与设置不一致。', '按设置重新生成', '保持不变');
    if (pick === '按设置重新生成') ensureConfig(true);
  }

  // Clean environment: the extension host's VSCODE_* / ELECTRON_* variables would make the
  // `code` CLI talk to this instance instead of starting the separate one.
  const env = { CODEX_HOME: home, [ENV_KEY]: key };
  for (const k of ['HOME', 'USER', 'LOGNAME', 'SHELL', 'LANG', 'LC_ALL', 'TMPDIR', 'PATH', 'DISPLAY', 'WAYLAND_DISPLAY',
    'XDG_RUNTIME_DIR', 'DBUS_SESSION_BUS_ADDRESS', 'SSH_AUTH_SOCK', 'USERPROFILE', 'APPDATA', 'LOCALAPPDATA', 'SystemRoot',
    'TEMP', 'TMP', 'HTTPS_PROXY', 'HTTP_PROXY', 'NO_PROXY', 'https_proxy', 'http_proxy', 'no_proxy']) {
    if (process.env[k]) env[k] = process.env[k];
  }
  const args = ['--user-data-dir', path.join(home, 'vscode-data'), '--new-window'];
  if (folder) args.push(folder);
  let stderr = '';
  const child = cp.spawn(cli, args, { env, detached: true, stdio: ['ignore', 'ignore', 'pipe'], shell: process.platform === 'win32' });
  child.stderr.on('data', (d) => { stderr += d.toString(); });
  child.on('error', (e) => vscode.window.showErrorMessage(`启动网关实例失败: ${e.message}`));
  child.on('exit', (code) => {
    if (code) vscode.window.showErrorMessage(`启动网关实例失败 (exit ${code}): ${stderr.trim().slice(0, 300)}`);
  });
  child.unref();
  vscode.window.setStatusBarMessage(`$(rocket) 正在打开网关 Codex 窗口${folder ? ': ' + path.basename(folder) : ''}`, 4000);
}

function currentFolder() {
  const f = vscode.workspace.workspaceFolders;
  return f && f.length && f[0].uri.scheme === 'file' ? f[0].uri.fsPath : undefined;
}

async function activate(context) {
  const provider = { getTreeItem: (e) => e, getChildren: () => [] }; // empty tree -> welcome content shows
  const view = vscode.window.createTreeView(VIEW_ID, { treeDataProvider: provider });
  await refreshContext(context);

  const onVisible = async () => {
    if (!view.visible || inside()) return;
    if (!cfg().get('launchOnIconClick')) return;
    if (!baseUrl() || !(await context.secrets.get(SECRET))) return; // not set up yet: stay on the panel with the "fill in key" button
    await launch(context, currentFolder());
    // Behave like a button: go back to the Explorer so the next click triggers again
    // and a restored sidebar never auto-launches on startup.
    setTimeout(() => vscode.commands.executeCommand('workbench.view.explorer'), 150);
  };
  const reg = (id, fn) => vscode.commands.registerCommand(id, fn);
  context.subscriptions.push(
    view,
    view.onDidChangeVisibility(onVisible),
    context.secrets.onDidChange((e) => { if (e.key === SECRET) refreshContext(context); }),
    reg('codexGateway.openCurrent', () => launch(context, currentFolder())),
    reg('codexGateway.openEmpty', () => launch(context, undefined)),
    reg('codexGateway.openPick', async () => {
      const pick = await vscode.window.showOpenDialog({ canSelectFolders: true, canSelectFiles: false, canSelectMany: false, openLabel: '用网关实例打开' });
      if (pick && pick[0]) launch(context, pick[0].fsPath);
    }),
    reg('codexGateway.setKey', () => setKey(context)),
    reg('codexGateway.setUrl', () => setUrl(context)),
    vscode.workspace.onDidChangeConfiguration((e) => { if (e.affectsConfiguration('codexGateway')) refreshContext(context); }),
    reg('codexGateway.clearKey', async () => { await context.secrets.delete(SECRET); await refreshContext(context); vscode.window.showInformationMessage('已删除保存的网关 key。'); }),
    reg('codexGateway.test', () => testGateway(context, false)),
    reg('codexGateway.writeConfig', async () => {
      const ok = await vscode.window.showWarningMessage(`按当前设置重新生成 ${path.join(codexHome(), 'config.toml')}?原文件会另存为 config.toml.bak。`, { modal: true }, '重新生成');
      if (ok) { try { ensureConfig(true); vscode.window.showInformationMessage('已重新生成。'); } catch (e) { vscode.window.showErrorMessage(e.message); } }
    }),
    reg('codexGateway.openSettings', () => vscode.commands.executeCommand('workbench.action.openSettings', 'codexGateway')),
  );
  if (view.visible) onVisible(); // the click that activated the extension
}

function deactivate() {}
module.exports = { activate, deactivate, _test: { configToml, request, launch } };
